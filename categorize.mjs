/** ชั้น 1 — คำสำคัญ คืน null ถ้าไม่รู้จัก */
export function matchKeyword(text) {
  const t = ` ${String(text).toLowerCase()} `;
  for (const [cat, words] of RULES) {
    for (const w of words) if (t.includes(w.toLowerCase())) return { category: cat, by: 'keyword' };
  }
  return null;
}

/** ชั้น 2 — Jev (ต้องส่ง decide() กับรายชื่อหมวดเข้ามา) */
export async function askJev(decide, ollama, model, text, categories, signal) {
  const options = categories.map((c, i) => ({ id: i, label: HINTS[c] ? `${c} — ${HINTS[c]}` : c }));
  const r = await decide(ollama, model, {
    kind: 'choice',
    question: `รายจ่ายของบริษัทขายสกินแคร์ออนไลน์: "${text}"\nจัดอยู่ในหมวดบัญชีใด`,
    options,
  }, signal);
  return { category: categories[r.answer], by: 'jev', ms: r.ms };
}

/** รวมสองชั้น */
export async function categorize(text, categories, deps) {
  const hit = matchKeyword(text);
  if (hit) return { ...hit, ms: 0 };
  if (!deps) return { category: 'อื่น ๆ', by: 'fallback', ms: 0 };
  try {
    return await askJev(deps.decide, deps.ollama, deps.model, text, categories, deps.signal);
  } catch {
    return { category: 'อื่น ๆ', by: 'fallback', ms: 0 };
  }
}
